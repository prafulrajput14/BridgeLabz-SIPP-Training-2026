public class HarryAge {
    public static void main(String[] args) {
        // Create variable birthYear to store Harry's birth year
        int birthYear = 2000;
        
        // Create variable currentYear to store the current year
        int currentYear = 2024;
        
        // Calculate the age by subtracting birthYear from currentYear
        int age = currentYear - birthYear;
        
        // Print the result matching the output format: Harry's age in 2024 is ___
        System.out.println("Harry's age in " + currentYear + " is " + age);
    }
}
